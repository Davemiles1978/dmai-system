"""NCSL Token Table — 256 single-byte symbols."""

MAGIC = b"NC"
VERSION = 0x03

# Control (0x00-0x0F)
NOP, END, RETURN = 0x00, 0x05, 0x06
BREAK, CONTINUE, YIELD, RAISE = 0x07, 0x08, 0x0D, 0x0E

# Types (0x10-0x1F)
I8, I16, I32, I64 = 0x10, 0x11, 0x12, 0x13
F32, F64, BOOL, STR = 0x14, 0x15, 0x16, 0x17
BYTES, LIST, DICT, TUPLE, SET, NONE = 0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1D

# Operators (0x20-0x3F)
ADD, SUB, MUL, DIV, MOD, POW, NEG = 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26
AND, OR, NOT = 0x29, 0x2A, 0x2B
EQ, NEQ, LT, GT, LTE, GTE = 0x32, 0x33, 0x34, 0x35, 0x36, 0x37
IN, NOT_IN = 0x3A, 0x3B

# Flow (0x40-0x5F)
IF, ELIF, ELSE = 0x40, 0x41, 0x42
WHILE, FOR = 0x47, 0x48
RANGE = 0x4A

# Functions/Classes (0x60-0x7F)
FUNC_DEF, CLASS_DEF, METHOD_DEF = 0x60, 0x61, 0x62
CALL, LAMBDA = 0x68, 0x6F

# I/O (0x80-0x9F)
PRINT, OPEN, READ, WRITE = 0x80, 0x82, 0x84, 0x85
JSON_LOAD, JSON_DUMP = 0x8A, 0x8B
HTTP_GET, HTTP_POST = 0x8C, 0x8D

# Common ops (0xA0-0xBF)
MAP, FILTER, SORT = 0xA0, 0xA1, 0xA3
ENUMERATE, ZIP, LEN = 0xA5, 0xA6, 0xA8

# Errors (0xC0-0xDF)
TRY, EXCEPT, FINALLY, ASSERT = 0xC0, 0xC1, 0xC2, 0xC6

# Custom (0xF0-0xFF)
CUSTOM_BASE = 0xF0
